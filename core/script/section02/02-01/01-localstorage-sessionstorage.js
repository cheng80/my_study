// 1. 로컬 스토리지에 데이터를 저장하고 가져오는 방법
// 로컬 스토리지에 데이터 저장
localStorage.setItem('아이디', 1234);
// 로컬 스토리지에서 데이터 가져오기
localStorage.getItem('아이디'); // 1234

// 2. 세션 스토리지에 데이터를 저장하고 가져오는 방법
// 세션 스토리지에 데이터 저장
sessionStorage.setItem('아이디', 1234);
// 세션 스토리지에서 데이터 가져오기
sessionStorage.getItem('아이디'); // 1234   
